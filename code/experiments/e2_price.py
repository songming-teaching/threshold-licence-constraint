"""E2: the price law.

  (a) b_K vs K, Gaussian: exact quadrature vs sqrt(2 ln K) vs the corrected expansion
  (b) heavy tails t_nu: the K^{1/nu} law, and exact/asymptotic convergence
  (c) multiple thresholds: cost tracks d*K, not K
Outputs exp/data/e2_price.csv, exp/data/e2_summary.json
"""
import json
import os
import time
from math import gamma, pi, sqrt

import numpy as np
from scipy.integrate import quad
from scipy.stats import norm, t as tdist

SEED = 20261102
HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(os.path.dirname(HERE), "data")
os.makedirs(DATA, exist_ok=True)
GAMMA = 0.5772156649015329


def b_gauss(K):
    f = lambda t: 1.0 - norm.cdf(t) ** K - norm.sf(t) ** K
    return float(quad(f, 0.0, sqrt(2 * np.log(K)) + 14.0, limit=600,
                      epsabs=1e-12, epsrel=1e-12)[0])


def b_t(nu, K):
    scale = sqrt((nu - 2.0) / nu)

    def g(s):
        x = np.exp(s)
        F = float(tdist.cdf(x / scale, nu))
        if F >= 1.0:
            return 0.0
        return (1.0 - F ** K - (1.0 - F) ** K) * x
    return float(quad(g, -40.0, np.log(1e7), limit=500, epsabs=1e-11)[0])


def tail_const(nu):
    C_std = gamma((nu + 1) / 2.0) * nu ** (nu / 2.0 - 1.0) / (sqrt(pi) * gamma(nu / 2.0))
    return C_std * ((nu - 2.0) / nu) ** (nu / 2.0)


rows = []
t0 = time.time()

# ---------------------------------------------------------------- (a) Gaussian
print("=" * 74)
print("(a) Gaussian: exact vs two closed forms")
print("=" * 74)
print(f"  {'K':>8s} {'exact':>9s} {'sqrt2lnK':>9s} {'centre':>9s} {'centre+g/a':>11s} "
      f"{'err%':>7s}")
for K in (2, 5, 10, 32, 100, 316, 1000, 3162, 10000, 31623, 100000):
    ex = b_gauss(K)
    a = sqrt(2 * np.log(K))
    c = a - (np.log(np.log(K)) + np.log(4 * pi)) / (2 * a)
    m = c + GAMMA / a
    rows.append(dict(panel="gauss", K=K, exact=ex, sqrt2=a, centre=c, mod=m,
                     err_pct=100 * abs(m - ex) / ex,
                     err_sqrt_pct=100 * abs(a - ex) / ex))
    print(f"  {K:8d} {ex:9.4f} {a:9.4f} {c:9.4f} {m:11.4f} {100*abs(m-ex)/ex:6.2f}%")

# ---------------------------------------------------------------- (b) tails
print()
print("=" * 74)
print("(b) heavy tails: exact vs (K C)^(1/nu) Gamma(1-1/nu)")
print("=" * 74)
print(f"  {'nu':>3s} {'K':>7s} {'exact':>10s} {'asym':>10s} {'ratio':>7s}")
for nu in (3, 4, 6):
    C = tail_const(nu)
    for K in (100, 1000, 10000, 100000):
        ex = b_t(nu, K)
        asym = (K * C) ** (1.0 / nu) * gamma(1.0 - 1.0 / nu)
        rows.append(dict(panel="tail", nu=nu, K=K, exact=ex, asym=asym, ratio=ex / asym,
                         C=C))
        print(f"  {nu:3d} {K:7d} {ex:10.4f} {asym:10.4f} {ex/asym:7.3f}")
    print()

# ---------------------------------------------------------------- (c) multi
print("=" * 74)
print("(c) d coordinatewise thresholds: cost tracks d*K")
print("=" * 74)
rng = np.random.default_rng(SEED)
print(f"  {'d':>4s} {'K':>6s} {'dK':>7s} {'MC':>9s} {'b_dK':>8s} {'b_K':>8s} {'se':>8s}")
for d in (1, 10, 100):
    for K in (100, 1000):
        reps = int(max(4000, 400000 // K))
        e = rng.standard_normal((reps, d, K))
        v = -np.min(e.reshape(reps, -1), axis=1)
        se = float(v.std(ddof=1) / sqrt(len(v)))
        mc = float(v.mean())
        rows.append(dict(panel="multi", d=d, K=K, MC=mc, se=se,
                         b_dK=b_gauss(d * K), b_K=b_gauss(K)))
        print(f"  {d:4d} {K:6d} {d*K:7d} {mc:9.4f} {b_gauss(d*K):8.4f} "
              f"{b_gauss(K):8.4f} {se:8.4f}")

# ---------------------------------------------------------------- write
import pandas as pd

df = pd.DataFrame(rows)
csv = os.path.join(DATA, "e2_price.csv")
with open(csv, "w", encoding="utf-8") as fh:
    fh.write(f"# E2 price law | generated by exp/code/e2_price.py | seed={SEED}\n")
    fh.write("# panel=gauss rows: exact by quadrature; sqrt2 = sqrt(2 ln K); "
             "centre = Gumbel centring; mod = centre + gamma/sqrt(2 ln K)\n")
    fh.write("# panel=tail rows: asym = (K C_nu)^(1/nu) Gamma(1-1/nu)\n")
    fh.write("# panel=multi rows: MC is a d*K block simulation, b_dK/b_K are quadrature\n")
df.to_csv(csv, mode="a", index=False)

g_ok = [r for r in rows if r["panel"] == "gauss" and r["K"] >= 10]
summ = dict(seed=SEED, elapsed_s=round(time.time() - t0, 2), n_rows=len(rows),
            gauss_max_err_pct=float(max(r["err_pct"] for r in g_ok)),
            gauss_sqrt2_max_err_pct=float(max(r["err_sqrt_pct"] for r in g_ok)),
            note="max errors reported over K>=10; the K=2,5 rows are outside the "
                 "expansion's domain of use and are kept only to show how fast it "
                 "deteriorates at the small-K end")
with open(os.path.join(DATA, "e2_summary.json"), "w", encoding="utf-8") as fh:
    json.dump(summ, fh, indent=2)
print(f"\nwrote {csv}  ({time.time()-t0:.1f}s)")
print(f"  corrected expansion max error: {summ['gauss_max_err_pct']:.2f}%")
print(f"  bare sqrt(2 ln K) max error : {summ['gauss_sqrt2_max_err_pct']:.2f}%")
